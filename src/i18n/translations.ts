export function normalizeLanguage(lang?: string | null): Language {
  if (!lang) return 'en';
  const l = lang.toLowerCase().trim();
  if (l === 'hi' || l === 'hindi' || l === 'हिंदी') return 'hi';
  if (l === 'bn' || l === 'bengali' || l === 'bangla' || l === 'বাংলা') return 'bn';
  return 'en';
}

export function getTranslation(key: string, lang: Language = 'en', fallback?: string): string {
  const normalized = normalizeLanguage(lang);
  const langDict = translations[normalized] || translations.en;
  if (langDict[key]) {
    return langDict[key];
  }
  if (translations.en[key]) {
    return translations.en[key];
  }
  return fallback || key;
}
